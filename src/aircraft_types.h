static const size_t TYPE_NAMES_COUNT = sizeof(TYPE_NAMES)/sizeof(TYPE_NAMES[0]);

// Returns the full name for an ICAO type designator, or "" if unknown.
inline String aircraftFullName(const String& code){
  if(code.length()==0) return "";
  for(size_t i=0;i<TYPE_NAMES_COUNT;i++){
    if(code.equalsIgnoreCase(TYPE_NAMES[i].code)) return String(TYPE_NAMES[i].name);
  }
  return "";
}
